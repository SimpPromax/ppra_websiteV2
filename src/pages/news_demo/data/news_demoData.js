// Helper functions
export const getCategories = () => {
  const categories = ['All', ...new Set(newsData.map(item => item.category))];
  return categories;
};

export const getCategoryCount = (category) => {
  if (category === 'All') return newsData.length;
  return newsData.filter(item => item.category === category).length;
};

export const getFilteredNews = (category) => {
  if (category === 'All') return newsData;
  return newsData.filter(item => item.category === category);
};

export const getFeaturedNews = () => {
  return newsData.filter(item => item.isFeatured);
};

export const getLatestNews = (limit = 6) => {
  return [...newsData]
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .slice(0, limit);
};

export const getNewsBySlug = (slug) => {
  return newsData.find(item => item.slug === slug);
};

export const getRelatedNews = (currentId, limit = 3) => {
  return newsData
    .filter(item => item.id !== currentId)
    .slice(0, limit);
};